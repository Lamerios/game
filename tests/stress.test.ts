describe('russian stress', () => {
  it('has none of the known wrong stresses', () => {
    const clips = allClips([...allNoteTexts(), ...allPuzzleTexts()]);
    const L = 'А-Яа-яЁё+';
    const bad: string[] = [];
    for (const [id, text] of clips) {
      if (id.startsWith('en.')) continue;
      for (const w of WRONG) {
        const re = new RegExp(`(?<![${L}])${w.replace(/\+/g, '\\+')}(?![${L}])`, 'i');
        if (re.test(text)) bad.push(`${w} in ${id}`);
      }
    }
    expect(bad).toEqual([]);
  });
});
